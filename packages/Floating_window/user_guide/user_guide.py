from PyQt6.QtWidgets import (QDialog, QVBoxLayout, QHBoxLayout, QPushButton,
                             QLabel, QScrollArea, QWidget, QFrame, QTreeWidget,
                             QTreeWidgetItem, QTextBrowser, QSplitter)
from PyQt6.QtCore import Qt


class DocumentationDialog(QDialog):
    """Диалог с документацией в стиле HTML страницы"""

    def __init__(self, parent=None):
        super().__init__(parent)
        self.setWindowTitle("Документация - Конфософт")
        self.setMinimumSize(1000, 700)

        self.initUI()
        self.load_documentation()

    def initUI(self):
        """Инициализация интерфейса"""
        main_layout = QHBoxLayout(self)
        main_layout.setSpacing(0)
        main_layout.setContentsMargins(0, 0, 0, 0)

        # Сплиттер для разделения меню и контента
        splitter = QSplitter(Qt.Orientation.Horizontal)

        # Левая часть - дерево с темами
        left_widget = QWidget()
        left_layout = QVBoxLayout(left_widget)
        left_layout.setContentsMargins(5, 5, 5, 5)
        left_layout.setSpacing(5)

        # Заголовок
        title_label = QLabel("Содержание")
        title_label.setStyleSheet("font-weight: bold; font-size: 14px; padding: 5px;")
        left_layout.addWidget(title_label)

        # Дерево тем
        self.tree = QTreeWidget()
        self.tree.setHeaderHidden(True)
        self.tree.setMinimumWidth(250)
        self.tree.itemClicked.connect(self.on_tree_item_clicked)
        left_layout.addWidget(self.tree)

        # Правая часть - контент
        right_widget = QWidget()
        right_layout = QVBoxLayout(right_widget)
        right_layout.setContentsMargins(10, 10, 10, 10)

        # Браузер для отображения HTML
        self.content_browser = QTextBrowser()
        self.content_browser.setOpenExternalLinks(True)

        self.content_browser.document().setDocumentMargin(20)

        right_layout.addWidget(self.content_browser)

        # Кнопка закрытия
        button_layout = QHBoxLayout()
        button_layout.addStretch()
        close_btn = QPushButton("Закрыть")
        close_btn.setFixedSize(100, 30)
        close_btn.clicked.connect(self.accept)
        button_layout.addWidget(close_btn)
        right_layout.addLayout(button_layout)

        # Добавляем виджеты в сплиттер
        splitter.addWidget(left_widget)
        splitter.addWidget(right_widget)
        splitter.setSizes([300, 700])

        main_layout.addWidget(splitter)

